def area(a ,h):
    '''
    Параметры:
        a : сторона треугольника 
        h : высота треугольника к стороне a
    Возращаемые значения:
        площадь треугольника
    '''
    return a * h / 2

def perimeter(a, b, c):
    '''Принимает стороны треугольика a,b,c, возращает периметр'''
    return a + b + c