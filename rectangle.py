def area(a,b):
    '''
    Параметры:
        a,b стороны прямоугольника
    
    Возращаемые значения:
        площадь прямольгольника
    '''
    return a * b

def perimeter(a,b):
    '''
    Принимает:
        a,b стороны прямоугольника

    Возращаемые значения:
        периметр прямоугольника
    '''
    return 2 * (a + b)

    